def bootstrap_ci(
    values,
    statistic_func,
    n_bootstrap=5000,
    confidence=0.95,
    random_state=42
):
    """
    Non-parametric bootstrap confidence interval.
    """

    values = np.asarray(
        values,
        dtype=float
    )

    values = values[
        np.isfinite(values)
    ]

    if len(values) == 0:
        return np.nan, np.nan, np.nan

    rng = np.random.default_rng(
        random_state
    )

    n = len(values)

    bootstrap_statistics = np.empty(
        n_bootstrap,
        dtype=float
    )

    for i in range(n_bootstrap):

        sample = rng.choice(
            values,
            size=n,
            replace=True
        )

        bootstrap_statistics[i] = statistic_func(
            sample
        )

    lower_percentile = (
        (1.0 - confidence) / 2.0
    ) * 100.0

    upper_percentile = (
        1.0 - (1.0 - confidence) / 2.0
    ) * 100.0

    lower = np.percentile(
        bootstrap_statistics,
        lower_percentile
    )

    upper = np.percentile(
        bootstrap_statistics,
        upper_percentile
    )

    observed = statistic_func(
        values
    )

    return (
        float(observed),
        float(lower),
        float(upper)
    )


def safe_wilcoxon(values):
    """
    Wilcoxon signed-rank test against zero.
    """

    values = np.asarray(
        values,
        dtype=float
    )

    values = values[
        np.isfinite(values)
    ]

    if len(values) == 0:
        return np.nan, np.nan

    if np.allclose(
        values,
        0.0
    ):
        return 0.0, 1.0

    try:

        result = wilcoxon(
            values,
            alternative="two-sided",
            zero_method="wilcox",
            method="auto"
        )

        return (
            float(result.statistic),
            float(result.pvalue)
        )

    except Exception:

        return np.nan, np.nan


def holm_correction(
    p_values,
    alpha=0.05
):
    """
    Holm-Bonferroni multiple-comparison correction.
    """

    p_values = np.asarray(
        p_values,
        dtype=float
    )

    n = len(p_values)

    order = np.argsort(
        p_values
    )

    adjusted = np.empty(
        n,
        dtype=float
    )

    for rank, index in enumerate(order):

        adjusted[index] = (
            (n - rank)
            * p_values[index]
        )

    # Enforce monotonicity
    for i in range(1, n):

        current_index = order[i]
        previous_index = order[i - 1]

        adjusted[current_index] = max(
            adjusted[current_index],
            adjusted[previous_index]
        )

    adjusted = np.minimum(
        adjusted,
        1.0
    )

    reject = adjusted < alpha

    return (
        adjusted,
        reject
    )


