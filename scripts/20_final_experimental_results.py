def load_csv(key, required=True):
    path = PATHS[key]
    if not os.path.exists(path):
        if required:
            raise FileNotFoundError(
                f"Required input missing for '{key}': {path}")
        print(f"  [optional, skipped] {key} not found at: {path}")
        return None
    df = pd.read_csv(path)
    print(
        f"  Loaded '{key}': {df.shape[0]} rows x {df.shape[1]} cols  <- {path}")
    return df


def make_pair_label(a, b):
    return f"{a}-{b}"


