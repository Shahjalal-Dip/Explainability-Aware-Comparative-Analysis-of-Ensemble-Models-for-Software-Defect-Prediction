def build_final_model_performance():
    print("\n[1/4] Building final_model_performance.csv ...")

    cv_df = load_csv("cv_performance")
    test_df = load_csv("test_performance")

    cv_df = cv_df.rename(columns={
        "Overall_Rank": "CV_Rank",
        "F1_Mean": "CV_F1_Mean", "F1_STD": "CV_F1_STD",
        "MCC_Mean": "CV_MCC_Mean", "MCC_STD": "CV_MCC_STD",
        "ROC_AUC_Mean": "CV_ROC_AUC_Mean", "ROC_AUC_STD": "CV_ROC_AUC_STD",
        "PR_AUC_Mean": "CV_PR_AUC_Mean", "PR_AUC_STD": "CV_PR_AUC_STD",
    })

    test_df = test_df.rename(columns={
        "Rank_by_F1": "Test_Rank",
        "Accuracy": "Test_Accuracy", "Precision": "Test_Precision",
        "Recall": "Test_Recall", "Specificity": "Test_Specificity",
        "F1": "Test_F1", "MCC": "Test_MCC",
        "ROC_AUC": "Test_ROC_AUC", "PR_AUC": "Test_PR_AUC",
        "TN": "Test_TN", "FP": "Test_FP", "FN": "Test_FN", "TP": "Test_TP",
    })

    merged = cv_df.merge(test_df, on="Model", how="outer")

    keep_cols = [
        "Model",
        "CV_Rank", "CV_F1_Mean", "CV_F1_STD", "CV_MCC_Mean", "CV_MCC_STD",
        "CV_ROC_AUC_Mean", "CV_ROC_AUC_STD", "CV_PR_AUC_Mean", "CV_PR_AUC_STD",
        "Selected_Training_Strategy",
        "Test_Rank", "Test_Accuracy", "Test_Precision", "Test_Recall",
        "Test_Specificity", "Test_F1", "Test_MCC", "Test_ROC_AUC", "Test_PR_AUC",
        "Test_TN", "Test_FP", "Test_FN", "Test_TP",
    ]
    keep_cols = [c for c in keep_cols if c in merged.columns]
    merged = merged[keep_cols].sort_values("CV_Rank")

    out_path = os.path.join(OUTPUT_DIR, "final_model_performance.csv")
    merged.to_csv(out_path, index=False)
    print(f"  -> wrote {out_path}")
    return merged


