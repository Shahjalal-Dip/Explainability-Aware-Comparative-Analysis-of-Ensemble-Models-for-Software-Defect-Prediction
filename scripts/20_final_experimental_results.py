def build_final_shap_consistency():
    print("\n[2/4] Building final_shap_consistency.csv ...")

    global_df = load_csv("unified_global")
    local_summary_df = load_csv("unified_local_summary")
    stat_df = load_csv("stat_validation", required=False)

    merged = global_df.merge(
        local_summary_df, on=["Model_A", "Model_B"], how="left"
    )

    if stat_df is not None:
        stat_cols = [
            "Model_A", "Model_B",
            "Wilcoxon_Spearman_Statistic", "Wilcoxon_Spearman_Raw_P",
            "Wilcoxon_Spearman_Holm_P", "Significant_After_Holm",
        ]
        stat_cols = [c for c in stat_cols if c in stat_df.columns]
        merged = merged.merge(stat_df[stat_cols], on=[
                              "Model_A", "Model_B"], how="left")

    merged.insert(2, "Model_Pair", merged["Model_A"] + "-" + merged["Model_B"])
    merged = merged.sort_values("Global_Spearman", ascending=False)

    out_path = os.path.join(OUTPUT_DIR, "final_shap_consistency.csv")
    merged.to_csv(out_path, index=False)
    print(f"  -> wrote {out_path}")
    return merged


