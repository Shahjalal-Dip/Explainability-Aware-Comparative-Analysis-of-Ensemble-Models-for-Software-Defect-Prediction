def build_final_ceci_results():
    print("\n[3/4] Building final_ceci_results.csv ...")

    pairwise_df = load_csv("ceci_pairwise")
    component_df = load_csv("ceci_component")
    overall_df = load_csv("ceci_overall")

    pairwise_out = pairwise_df.copy()
    pairwise_out.insert(0, "Result_Type", "Pairwise")

    overall_row = pd.DataFrame([{
        "Result_Type": "Overall",
        "Model_Pair": "ALL_PAIRS",
        "Pairwise_CECI": overall_df.loc[0, "Overall_CECI"],
        "CECI_Rank": np.nan,
        "Global_CECI_Component": overall_df.loc[0, "Global_CECI"],
        "Local_CECI_Component": overall_df.loc[0, "Local_CECI"],
    }])

    component_out = component_df.copy()
    component_out.insert(0, "Result_Type", "Component")
    component_out = component_out.rename(columns={
        "Component": "Model_Pair",
        "Normalized_Score": "Pairwise_CECI",
        "Weight": "CECI_Rank",  # repurposed column holds the component weight here
    })

    combined = pd.concat(
        [pairwise_out, overall_row, component_out],
        ignore_index=True, sort=False
    )

    out_path = os.path.join(OUTPUT_DIR, "final_ceci_results.csv")
    combined.to_csv(out_path, index=False)
    print(f"  -> wrote {out_path}")

    return {
        "pairwise": pairwise_df,
        "overall": overall_df,
        "component": component_df,
    }


