def per_model_average_ceci(pairwise_df):
    """Average pairwise CECI involving each model -> per-model consistency score."""
    long_rows = []
    for _, r in pairwise_df.iterrows():
        a, b = r["Model_Pair"].split("-")
        long_rows.append((a, r["Pairwise_CECI"]))
        long_rows.append((b, r["Pairwise_CECI"]))
    long_df = pd.DataFrame(long_rows, columns=["Model", "Pairwise_CECI"])
    avg = long_df.groupby(
        "Model")["Pairwise_CECI"].mean().sort_values(ascending=False)
    return avg


